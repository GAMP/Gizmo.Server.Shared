using System.ComponentModel.DataAnnotations;
using System.Net;
using Gizmo.Exceptions;
using Gizmo.Web.Api.Models;

namespace Gizmo.Server.Exceptions
{
    /// <summary>
    /// User login exception.
    /// </summary>
    [ExceptionFilterCode(ExceptionCode.UserLogin)]
    [Name("User login error", nameof(Shared.Resources.Autogenerated.Resources.EXCEPTION_TYPE_USER_LOGIN_NAME))]
    [ExtendedDescription("User login related error", nameof(Shared.Resources.Autogenerated.Resources.EXCEPTION_TYPE_USER_LOGIN_DESCRIPTION))]
    public class UserLoginException : ErrorCodeExceptionBase<LoginResult>
    {
        #region CONSTRUCTOR

        /// <summary>
        /// Creates new instance.
        /// </summary>
        /// <param name="errorCode">Error code.</param>
        /// <param name="httpStatusCode">Response http status code.</param>
        public UserLoginException(LoginResult errorCode, HttpStatusCode httpStatusCode = HttpStatusCode.Unauthorized) : base($"User login failed: {errorCode}.", errorCode)
        {
            HttpStatusCode = httpStatusCode;
        }

        #endregion

        #region PROPERTIES

        /// <summary>
        /// Gets response http status code.
        /// </summary>
        public HttpStatusCode HttpStatusCode { get; }

        #endregion
    }
}
